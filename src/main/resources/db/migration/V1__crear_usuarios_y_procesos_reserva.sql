CREATE TABLE app_user (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    login VARCHAR(50) NOT NULL CHECK (btrim(login) <> ''),
    password_hash VARCHAR(255) NOT NULL CHECK (btrim(password_hash) <> ''),
    first_name VARCHAR(100),
    last_name VARCHAR(100),
    email VARCHAR(254),
    image_url VARCHAR(256),
    lang_key VARCHAR(10),
    activated BOOLEAN NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE UNIQUE INDEX ux_app_user_login ON app_user (lower(login));
CREATE UNIQUE INDEX ux_app_user_email ON app_user (lower(email)) WHERE email IS NOT NULL;

CREATE TABLE user_authority (
    user_id BIGINT NOT NULL REFERENCES app_user(id),
    authority VARCHAR(50) NOT NULL CHECK (btrim(authority) <> ''),
    PRIMARY KEY (user_id, authority)
);

CREATE TABLE reservation_process (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_user(id),
    hold_id VARCHAR(255) UNIQUE,
    reservation_process_id VARCHAR(255) UNIQUE,
    reservation_id BIGINT UNIQUE,
    professional_id BIGINT NOT NULL,
    appointment_date DATE NOT NULL,
    start_time TIME NOT NULL,
    end_time TIME,
    status VARCHAR(50) NOT NULL CHECK (btrim(status) <> ''),
    expires_at TIMESTAMP WITH TIME ZONE,
    professional_first_name VARCHAR(100),
    professional_last_name VARCHAR(100),
    cancellation_reason VARCHAR(500),
    confirmed_at TIMESTAMP WITH TIME ZONE,
    cancelled_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    version BIGINT NOT NULL DEFAULT 0
);

CREATE INDEX ix_reservation_process_user_date ON reservation_process (user_id, appointment_date);
